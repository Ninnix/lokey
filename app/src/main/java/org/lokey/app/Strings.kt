    fun text(context:Context,value:String,vararg args:Any):String {
        val id=ids[value]
        if(id!=null) return if(args.isEmpty()) context.getString(id) else context.getString(id,*args)
        if(args.isNotEmpty()) return String.format(context.uiLocale(),value,*args)
        val mapping=LanguageLayouts.all[value]
        if(mapping!=null) return Locale.forLanguageTag(mapping.code).getDisplayLanguage(context.uiLocale())
        if(value.contains("\n")) return value.split('\n').joinToString("\n") { text(context,it) }
        if(value.contains(" · ")) return value.split(" · ").joinToString(" · ") { text(context,it) }
        return value
    }
}

